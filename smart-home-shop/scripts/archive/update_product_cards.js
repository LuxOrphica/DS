let updated = 0;
let notFound = 0;

// Обновляем каждый товар в БД
for (const [article, pdfInfo] of Object.entries(pdfData)) {
  // Ищем товар в БД
  const product = db.prepare('SELECT id, name FROM products WHERE article = ? OR id = ?').get(article, article);
  
  if (!product) {
    // Пробуем найти по частичному совпадению
    const partialMatch = db.prepare('SELECT id, article, name FROM products WHERE article LIKE ? OR id LIKE ?').get(`%${article}%`, `%${article}%`);
    
    if (!partialMatch) {
      console.log(`⚠ Товар не найден: ${article}`);
      notFound++;
      continue;
    }
  }
  
  const productId = product ? product.id : null;
  if (!productId) continue;
  
  // Получаем описание и характеристики
  const description = productDescriptions[article] || `Оборудование Larnitech ${article}. Германское качество, надежная проводная технология.`;
  const specs = specsByType[article] || '{"производитель": "Larnitech", "страна": "Германия", "гарантия": "2 года"}';
  
  // Обновляем товар в БД
  try {
    const result = db.prepare(`
      UPDATE products 
      SET description = ?, specs = ?, brand = 'Larnitech', source_url = 'https://larnitech-rus.ru/'
      WHERE id = ?
    `).run(description, specs, productId);
    
    if (result.changes > 0) {
      updated++;
      console.log(`✓ ${article} - обновлено`);
    }
  } catch (err) {
    console.error(`✗ ${article}: ${err.message}`);
  }
}

console.log(`\n✅ Обновлено ${updated} товаров`);
console.log(`⚠ Не найдено в БД: ${notFound} товаров`);

db.close();
